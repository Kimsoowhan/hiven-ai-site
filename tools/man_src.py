def build():
    out = dict(steps=STEPS, head=COMMON_HEAD, manuals=M, emergency=EMERGENCY, bench=BENCH, law=LAW, damage=DMG,
               follow=FOLLOW, mistakes=CASE_MISTAKES, expand=EXPAND, cross=[dict(n=i+1, name=STEPS[i], rows=[dict(code=m['code'], label=m['name'], do=m['steps'][i]['do'], say=m['steps'][i]['say']) for m in M]) for i in range(12)])
    json.dump(out, open(os.path.join(ROOT, 'manuals.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    return out

def md(m, d):
    s = ['# %s (%s)' % (m['name'], m['code']), '', '대상: ' + m['target'], '목적: ' + m['purpose'], '사용 시점: ' + m['when'],
         '담당·호출: ' + m['owner'], '창구: ' + m['channel'], '발령권자: ' + COMMON_HEAD['발령권자'], '제1원칙: ' + COMMON_HEAD['원칙'], '',
         '## 경보 12단계별 해야 할 일', '', '| 단계 | 해야 할 일 | 안내·응대·보고 문구 |', '|---|---|---|']
    for r in m['steps']:
        s.append('| %d %s | %s | %s |' % (r['n'], r['name'], r['do'], r['say']))
    s += ['', '## 비상체계 가동·해제']
    for k, v in d['emergency'].items():
        s += ['', '### ' + k] + ['- ' + x for x in v]
    s += ['', '## 금지·주의'] + ['- ' + x for x in m['ban']]
    s += ['', '## 점검·훈련'] + ['- ' + x for x in m['drill']]
    s += ['', '## 기록 서식', m['form'], '', '## 법정 기한·통지 항목(공통)', '', '| 근거 | 기한·내용 | 확인 상태 |', '|---|---|---|']
    s += ['| %s | %s | %s |' % tuple(x) for x in d['law']]
    s += ['', '## 조치 후 예측 가능한 피해 → 예방 조치', '', '| 조치 | 예상되는 피해 | 예방 조치 | 근거 |', '|---|---|---|---|']
    s += ['| %s | %s | %s | %s |' % tuple(x) for x in d['damage']]
    s += ['', '## 후속 요건'] + ['- ' + x for x in d['follow']]
    s += ['', '## 확장(B2C → B2B → B2G) 시 보안체계 요구', '', '| 단계 | 추가되는 요구 | 보안체계 영향 | 선행 조건 | 확인 상태 |', '|---|---|---|---|---|']
    s += ['| %s | %s | %s | %s | %s |' % tuple(x) for x in d['expand']]
    s += ['', '## 벤치마킹 근거', '', '| 출처 | 핵심 | 반영 | 확인 상태 |', '|---|---|---|---|']
    s += ['| %s | %s | %s | %s |' % tuple(x) for x in d['bench']]
    return '\n'.join(s) + '\n'

